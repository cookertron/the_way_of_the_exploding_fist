#!/usr/bin/env python3
"""
build.py -- assemble the shipped single file from the template (manual 7.7/12).

Driven by port.json at the repo root:

    template   the page source (web/template.html)
    out        the built file (web/<game>.html)
    includes   { marker-name: path }  -- each `/*#include NAME*/` in the
               template is replaced by that file's text (this is how the
               platform runtime is inlined ahead of the engine)
    assets     [ { key, file, required, note } ]  -- each JSON file becomes
               assets[key] in the payload; a missing REQUIRED asset fails the
               build, a missing optional one prints a NOTE

The rules that matter, kept from the case study:

  - the generated file says loudly that it is generated and which file to
    edit;
  - the asset JSON is inlined inside a script element of a NON-EXECUTABLE
    type, with the sequence "</" escaped so the payload cannot break out;
  - the escaped text is RE-PARSED to prove the escaping held, and the build
    FAILS if any placeholder or include marker survives substitution.

A port adds its own shape assertions on the assets it extracts ("the font is
106 glyphs of 8 bytes", "307 dungeon records") right here, so a stale
extractor output cannot ship.  See the case study's build.py for the idea:
every count that the engine depends on is asserted at build time.

A fixture's "_stamp" (manual 12.3) is left out of the page: it says what
produced the evidence, not what the game needs.  build/built.json records
the build -- the page's hash, each asset's content hash, the hashes of the
build's own inputs -- for rig.done() to carry into build/gate.json when the
whole suite passes (tools/stamp.py reads both).
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import stamp  # noqa: E402


def load_manifest():
    p = os.path.join(ROOT, 'port.json')
    if not os.path.exists(p):
        sys.exit('BUILD FAILED: port.json missing at the repo root')
    return json.load(open(p, encoding='utf-8'))


def main():
    cfg = load_manifest()
    tpl_rel = cfg.get('template', 'web/template.html')
    out_rel = cfg.get('out') or ('web/%s.html' % cfg.get('name', 'game'))
    tpl_path = os.path.join(ROOT, tpl_rel)
    out_path = os.path.join(ROOT, out_rel)
    if not os.path.exists(tpl_path):
        sys.exit('BUILD FAILED: template %s missing' % tpl_rel)
    tpl = open(tpl_path, encoding='utf-8').read()

    # ---- includes -------------------------------------------------------
    for name, rel in (cfg.get('includes') or {}).items():
        marker = '/*#include %s*/' % name
        if marker not in tpl:
            sys.exit('BUILD FAILED: include marker %s missing from %s' % (marker, tpl_rel))
        src_path = os.path.join(ROOT, rel)
        if not os.path.exists(src_path):
            sys.exit('BUILD FAILED: include %s -> %s missing' % (name, rel))
        src = open(src_path, encoding='utf-8').read()
        tpl = tpl.replace(marker,
                          '/* ---- begin %s -- inlined by tools/build.py; edit %s ---- */\n'
                          % (name, rel) + src +
                          '\n/* ---- end %s ---- */' % name)
    left = re.findall(r'/\*#include ([^*]+)\*/', tpl)
    if left:
        sys.exit('BUILD FAILED: include marker(s) not in port.json: %s' % ', '.join(left))

    # ---- assets ---------------------------------------------------------
    assets, files = {}, {stamp.rel(__file__): None, tpl_rel: None, 'port.json': None}
    files.update({rel: None for rel in (cfg.get('includes') or {}).values()})
    for a in (cfg.get('assets') or []):
        rel = a['file']
        path = os.path.join(ROOT, rel)
        if not os.path.exists(path):
            note = a.get('note', '')
            if a.get('required', True):
                sys.exit('BUILD FAILED: %s missing%s' % (rel, ' -- ' + note if note else ''))
            print('NOTE: %s missing%s' % (rel, ' -- ' + note if note else ''))
            continue
        assets[a['key']] = json.load(open(path, encoding='utf-8'))
        if isinstance(assets[a['key']], dict):
            assets[a['key']].pop('_stamp', None)

    payload = json.dumps(assets, separators=(',', ':'))
    escaped = payload.replace('</', '<\\/')

    # prove the escaping held, before writing anything
    reparsed = json.loads(escaped.replace('<\\/', '</'))
    assert reparsed == assets, 'escaped payload does not round-trip'
    assert '</' not in escaped, 'payload can still break out of the script tag'

    if '__ASSETS__' not in tpl:
        sys.exit('BUILD FAILED: placeholder __ASSETS__ missing from template')
    banner = ('<!-- GENERATED by tools/build.py from %s -- '
              'DO NOT EDIT THIS FILE. Edit the template and rebuild. -->\n' % tpl_rel)
    out = banner + tpl.replace('__ASSETS__', escaped)
    if '__ASSETS__' in out:
        sys.exit('BUILD FAILED: placeholder survived substitution')

    # the inlined payload must still parse out of the BUILT file
    m = re.search(r'<script type="application/json" id="assets">(.*?)</script>',
                  out, re.S)
    if not m:
        sys.exit('BUILD FAILED: cannot find the asset script element in the output')
    json.loads(m.group(1).replace('<\\/', '</'))

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    open(out_path, 'w', encoding='utf-8').write(out)
    built = {'Purpose': 'what the last build put in the page; read by test/rig.js done() and tools/stamp.py',
             'out': out_rel, 'html': stamp.file_hash(out_rel),
             'files': {f: stamp.file_hash(f) for f in files},
             'assets': {k: [next(a['file'] for a in cfg['assets'] if a['key'] == k), stamp.content_hash(v)]
                        for k, v in assets.items()}}
    with open(os.path.join(ROOT, stamp.BUILT), 'w', encoding='utf-8') as f:
        json.dump(built, f, indent=1)
    print('payload %d bytes -> escaped %d bytes, re-parsed OK' % (len(payload), len(escaped)))
    print('wrote %s (%d bytes)' % (out_path, len(out)))


if __name__ == '__main__':
    main()
